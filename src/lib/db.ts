import { neon } from '@neondatabase/serverless';
import type { Copy } from '@/lib/i18n';

export function db() {
  if (!process.env.DATABASE_URL) return null;
  return neon(process.env.DATABASE_URL);
}

let schemaPromise: Promise<void> | undefined;
export function ensureSchema(): Promise<void> {
  const sql = db();
  if (!sql) return Promise.reject(new Error('DATABASE_URL não configurada.'));
  if (!schemaPromise) {
    schemaPromise = (async () => {
      await sql`CREATE TABLE IF NOT EXISTS site_settings (id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id=1), data JSONB NOT NULL DEFAULT '{}', updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`;
      await sql`CREATE TABLE IF NOT EXISTS blog_articles (slug TEXT PRIMARY KEY, data JSONB NOT NULL, published BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`;
      await sql`CREATE TABLE IF NOT EXISTS leads (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, business TEXT, email TEXT NOT NULL, phone TEXT, message TEXT NOT NULL, locale TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`;
      await sql`CREATE TABLE IF NOT EXISTS metrics (day DATE NOT NULL, pathname TEXT NOT NULL, event TEXT NOT NULL, total BIGINT NOT NULL DEFAULT 0, PRIMARY KEY (day,pathname,event))`;
      await sql`CREATE TABLE IF NOT EXISTS login_limits (key TEXT PRIMARY KEY, attempts INT NOT NULL DEFAULT 0, updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`;
      await sql`CREATE TABLE IF NOT EXISTS media (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, url TEXT NOT NULL, filename TEXT NOT NULL, content_type TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`;
      await sql`CREATE UNIQUE INDEX IF NOT EXISTS idx_media_url ON media(url)`;
      await sql`CREATE INDEX IF NOT EXISTS idx_leads_created ON leads(created_at DESC)`;
      await sql`CREATE INDEX IF NOT EXISTS idx_metrics_day ON metrics(day DESC)`;
    })().catch(e => { schemaPromise=undefined; throw e; });
  }
  return schemaPromise;
}

export type Overrides = Partial<Copy> & { storyTitle?: string; storyDescription?: string; ctaTitle?: string }; 
export type Settings = {
  locales?: Partial<Record<'pt'|'es'|'de'|'fr'|'en', Overrides>>;
  catalogUrl?: string; heroImage?: string; whatsappNumber?: string;
  googleVerification?: string; seoTitle?: string; seoDescription?: string;
};
export async function settings(): Promise<Settings> {
  const sql = db(); if (!sql) return {};
  try { await ensureSchema(); const r=await sql`SELECT data FROM site_settings WHERE id=1`; return (r[0]?.data ?? {}) as Settings; }
  catch (e) { console.error('[settings]',e); return {}; }
}
export async function saveSettings(data: Settings) {
  const sql=db(); if (!sql) throw new Error('DATABASE_URL não configurada.'); await ensureSchema();
  await sql`INSERT INTO site_settings(id,data) VALUES (1,${JSON.stringify(data)}::jsonb) ON CONFLICT (id) DO UPDATE SET data=EXCLUDED.data,updated_at=NOW()`;
}
